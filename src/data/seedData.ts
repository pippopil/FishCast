function makePolygon(centerLng: number, centerLat: number, rx: number, ry: number, skew = 0): [number, number][] {
  const pts: [number, number][] = [];
  const steps = 14;
  for (let i = 0; i < steps; i++) {
    const a = (i / steps) * Math.PI * 2;
    const wobble = 1 + 0.16 * Math.sin(a * 3 + centerLat * 10) + 0.08 * Math.cos(a * 2);
    const lng = centerLng + Math.cos(a) * rx * wobble + Math.sin(a) * skew;
    const lat = centerLat + Math.sin(a) * ry * wobble;
    pts.push([Number(lng.toFixed(6)), Number(lat.toFixed(6))]);
  }
  pts.push(pts[0]);
  return pts;
}

function makeRiverPolygon(points: [number, number][], halfWidthLng: number, halfWidthLat: number): [number, number][] {
  const left: [number, number][] = [];
  const right: [number, number][] = [];
  for (const [lng, lat] of points) {
    left.push([Number((lng - halfWidthLng).toFixed(6)), Number((lat + halfWidthLat).toFixed(6))]);
    right.unshift([Number((lng + halfWidthLng).toFixed(6)), Number((lat - halfWidthLat).toFixed(6))]);
  }
  const ring = [...left, ...right];
  ring.push(ring[0]);
  return ring;
}

